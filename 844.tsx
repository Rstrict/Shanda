/** Fisher-Yates 数组洗牌 */
function shuffleArray(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/** 生成会话队列中的单个题目项（每次生成自动打乱各空选项） */
function createSessionItem(base, isRetry, randomCloze, previous) {
  const question = randomCloze && !base.parts ? { ...base, ...buildDynamicCloze(base, previous) } : base;
  return {
    uid: `${question.id}_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    base,
    questionId: question.id,
    question,
    isRetry,
    shuffledOptions: question.blanks.map((b) => shuffleArray(b.options)),
  };
}

/** 获取今天的日期字符串 YYYY-MM-DD（支持模拟时间偏移） */
function getDateKey(timestamp) {
  const d = new Date(timestamp);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/** 格式化相对复习时间 */
function formatNextReview(nextReviewAt, now) {
  if (!nextReviewAt) return '未安排';
  const diff = nextReviewAt - now;
  if (diff <= 0) return '已到期';
  const mins = Math.ceil(diff / MINUTE);
  if (mins < 60) return `${mins} 分钟后`;
  const hours = Math.ceil(diff / HOUR);
  if (hours < 24) return `${hours} 小时后`;
  const days = Math.ceil(diff / DAY);
  return `${days} 天后`;
}

/** 解析答案模板为片段数组 */
function parseTemplateParts(template) {
  const regex = /\{\{(\d+)\}\}/g;
  const parts = [];
  let lastIndex = 0;
  let match;
  while ((match = regex.exec(template)) !== null) {
    if (match.index > lastIndex) {
      parts.push({ type: 'text', content: template.slice(lastIndex, match.index) });
    }
    parts.push({ type: 'blank', index: parseInt(match[1], 10) });
    lastIndex = regex.lastIndex;
  }
  if (lastIndex < template.length) {
    parts.push({ type: 'text', content: template.slice(lastIndex) });
  }
  return parts;
}

